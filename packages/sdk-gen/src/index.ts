import fs from "node:fs";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

export interface GenerateTypeScriptSdkOptions {
  openApiSpec: Record<string, any>;
  outDir: string;
  checkOnly?: boolean;
}

export interface GeneratedTypeScriptSdkArtifacts {
  contractsPath: string;
  schemaPath: string;
  clientPath: string;
  openApiJson: string;
  schemaDts: string;
  clientTs: string;
  drifted: boolean;
}

export const CLIENT_TS_TEMPLATE = `// Generated by @pands/sdk-gen — do not edit by hand
import createClient, { type Client } from "openapi-fetch";
import type { paths } from "./schema.js";

export type { paths };
export type PandApiClient = Client<paths>;

export interface CreatePandClientOptions {
  baseUrl?: string;
  getToken?: () => string | null | undefined | Promise<string | null | undefined>;
  fetch?: typeof globalThis.fetch;
  headers?: Record<string, string>;
}

export function createPandClient(options: CreatePandClientOptions = {}): PandApiClient {
  const client = createClient<paths>({
    baseUrl: options.baseUrl ?? "",
    fetch: options.fetch,
    headers: options.headers,
  });

  if (options.getToken) {
    client.use({
      async onRequest({ request }) {
        const token = await options.getToken?.();
        if (token) {
          request.headers.set("authorization", \`Bearer \${token}\`);
        }
        return request;
      },
    });
  }

  return client;
}

export const createPandSdk = createPandClient;
`;

export async function generateTypeScriptSdk(
  options: GenerateTypeScriptSdkOptions,
): Promise<GeneratedTypeScriptSdkArtifacts> {
  const openApiJson = `${JSON.stringify(options.openApiSpec, null, 2)}\n`;
  const ast = await openapiTS(options.openApiSpec as any);
  const schemaDts = `// Generated by @pands/sdk-gen — do not edit by hand\n${astToString(ast)}`;
  const clientTs = CLIENT_TS_TEMPLATE;

  const contractsDir = path.join(options.outDir, "packages", "contracts");
  const sdkSrcDir = path.join(options.outDir, "packages", "sdk", "src");

  const contractsPath = path.join(contractsDir, "openapi.json");
  const schemaPath = path.join(sdkSrcDir, "schema.d.ts");
  const clientPath = path.join(sdkSrcDir, "index.ts");

  const existingOpenApi = fs.existsSync(contractsPath)
    ? fs.readFileSync(contractsPath, "utf8")
    : null;
  const existingSchema = fs.existsSync(schemaPath) ? fs.readFileSync(schemaPath, "utf8") : null;

  const drifted = existingOpenApi !== openApiJson || existingSchema !== schemaDts;

  if (!options.checkOnly) {
    fs.mkdirSync(contractsDir, { recursive: true });
    fs.mkdirSync(sdkSrcDir, { recursive: true });
    fs.writeFileSync(contractsPath, openApiJson, "utf8");
    fs.writeFileSync(schemaPath, schemaDts, "utf8");
    if (!fs.existsSync(clientPath)) {
      fs.writeFileSync(clientPath, clientTs, "utf8");
    }
  }

  return {
    contractsPath,
    schemaPath,
    clientPath,
    openApiJson,
    schemaDts,
    clientTs,
    drifted,
  };
}

