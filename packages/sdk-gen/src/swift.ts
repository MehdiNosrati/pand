import fs from "node:fs";
import path from "node:path";

export interface GenerateSwiftSdkOptions {
  openApiSpec: Record<string, any>;
  outDir: string;
}

export interface GeneratedSwiftSdkArtifacts {
  openApiPath: string;
  configYamlPath: string;
  clientSwiftPath: string;
}

export function generateSwiftSdk(options: GenerateSwiftSdkOptions): GeneratedSwiftSdkArtifacts {
  const sdkDir = path.join(
    options.outDir,
    "apps",
    "ios",
    "Packages",
    "PandSDK",
    "Sources",
    "PandSDK",
  );
  fs.mkdirSync(sdkDir, { recursive: true });

  const openApiPath = path.join(sdkDir, "openapi.json");
  const configYamlPath = path.join(sdkDir, "openapi-generator-config.yaml");
  const clientSwiftPath = path.join(sdkDir, "PandAPIClient.swift");

  fs.writeFileSync(openApiPath, `${JSON.stringify(options.openApiSpec, null, 2)}\n`, "utf8");

  const configYaml = ["generate:", "  - types", "  - client", "accessModifier: public", ""].join(
    "\n",
  );
  fs.writeFileSync(configYamlPath, configYaml, "utf8");

  const schemas = (options.openApiSpec.components?.schemas ?? {}) as Record<string, any>;
  const modelStructs: string[] = [];
  for (const [rawSchemaName, schemaObj] of Object.entries(schemas)) {
    const schemaName = rawSchemaName.includes("_")
      ? rawSchemaName.slice(rawSchemaName.indexOf("_") + 1)
      : rawSchemaName;
    const props = (schemaObj?.properties ?? {}) as Record<string, any>;
    const requiredSet = new Set<string>(schemaObj?.required ?? []);
    const fields: string[] = [];
    for (const [propName, propDef] of Object.entries(props)) {
      let swiftType = "String";
      if (propDef.type === "boolean") swiftType = "Bool";
      else if (propDef.type === "integer") swiftType = "Int";
      else if (propDef.type === "number") swiftType = "Double";
      const optionalSuffix = requiredSet.has(propName) ? "" : "?";
      fields.push(`    public var ${propName}: ${swiftType}${optionalSuffix}`);
    }
    modelStructs.push(
      `public struct ${schemaName}: Codable, Identifiable, Sendable {\n${fields.join("\n")}\n}`,
    );
  }

  const clientSwift = `// Generated by @pands/sdk-gen — do not edit by hand
import Foundation

${modelStructs.join("\n\n")}

public actor PandAPIClient {
    public let baseURL: URL
    private let tokenProvider: @Sendable () -> String?

    public init(baseURL: URL, tokenProvider: @escaping @Sendable () -> String? = { nil }) {
        self.baseURL = baseURL
        self.tokenProvider = tokenProvider
    }

    public func request<T: Decodable>(
        path: String,
        method: String = "GET",
        body: Data? = nil
    ) async throws -> T {
        let url = baseURL.appendingPathComponent(path)
        var req = URLRequest(url: url)
        req.httpMethod = method
        req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        if let token = tokenProvider() {
            req.setValue("Bearer \\(token)", forHTTPHeaderField: "Authorization")
        }
        req.httpBody = body
        let (data, _) = try await URLSession.shared.data(for: req)
        return try JSONDecoder().decode(T.self, from: data)
    }
}
`;

  fs.writeFileSync(clientSwiftPath, clientSwift, "utf8");

  return {
    openApiPath,
    configYamlPath,
    clientSwiftPath,
  };
}
