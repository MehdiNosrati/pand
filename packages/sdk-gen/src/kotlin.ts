import fs from "node:fs";
import path from "node:path";

export interface GenerateKotlinSdkOptions {
  openApiSpec: Record<string, any>;
  outDir: string;
  projectName: string;
}

export interface GeneratedKotlinSdkArtifacts {
  modelsKtPath: string;
  apiKtPath: string;
}

export function generateKotlinSdk(options: GenerateKotlinSdkOptions): GeneratedKotlinSdkArtifacts {
  const snakeProject = options.projectName.replace(/-/g, "_");
  const sdkDir = path.join(
    options.outDir,
    "apps",
    "android",
    "app",
    "src",
    "main",
    "java",
    "dev",
    "mahdins",
    snakeProject,
    "sdk",
  );
  fs.mkdirSync(sdkDir, { recursive: true });

  const modelsKtPath = path.join(sdkDir, "Models.kt");
  const apiKtPath = path.join(sdkDir, "PandApi.kt");

  const schemas = (options.openApiSpec.components?.schemas ?? {}) as Record<string, any>;
  const dataClasses: string[] = [];
  for (const [rawSchemaName, schemaObj] of Object.entries(schemas)) {
    const schemaName = rawSchemaName.includes("_")
      ? rawSchemaName.slice(rawSchemaName.indexOf("_") + 1)
      : rawSchemaName;
    const props = (schemaObj?.properties ?? {}) as Record<string, any>;
    const requiredSet = new Set<string>(schemaObj?.required ?? []);
    const fields: string[] = [];
    for (const [propName, propDef] of Object.entries(props)) {
      let ktType = "String";
      if (propDef.type === "boolean") ktType = "Boolean";
      else if (propDef.type === "integer") ktType = "Int";
      else if (propDef.type === "number") ktType = "Double";
      const nullable = requiredSet.has(propName) ? "" : "? = null";
      fields.push(`    val ${propName}: ${ktType}${nullable}`);
    }
    dataClasses.push(`@Serializable\ndata class ${schemaName}(\n${fields.join(",\n")}\n)`);
  }

  const modelsKt = `// Generated by @pands/sdk-gen — do not edit by hand
package dev.mahdins.${snakeProject}.sdk

import kotlinx.serialization.Serializable

${dataClasses.join("\n\n")}
`;

  const apiKt = `// Generated by @pands/sdk-gen — do not edit by hand
package dev.mahdins.${snakeProject}.sdk

import retrofit2.http.Body
import retrofit2.http.DELETE
import retrofit2.http.GET
import retrofit2.http.POST
import retrofit2.http.Path

interface PandApi {
    @GET("/healthz")
    suspend fun healthz(): Map<String, String>
}
`;

  fs.writeFileSync(modelsKtPath, modelsKt, "utf8");
  fs.writeFileSync(apiKtPath, apiKt, "utf8");

  return {
    modelsKtPath,
    apiKtPath,
  };
}
